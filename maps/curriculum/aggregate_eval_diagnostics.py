#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
S2E V2 Evaluation Log Aggregator (KPI Analyzer)
Author: Lee Minseok
Description:
    Reads JSONL diagnostic outputs printed by S2EAutoEpisodeDiagnosticsRecorder,
    calculates key performance indicators (KPIs) like success rate, collision rate,
    deadlocks, lateral error, and outputs formatted Markdown tables grouped by
    difficulty level and scenario.
"""

import json
import argparse
import sys
from pathlib import Path
from collections import defaultdict
import numpy as np

def parse_args():
    parser = argparse.ArgumentParser(description="S2E V2 Episode Diagnostics Log Aggregator")
    parser.add_argument(
        "log_file", 
        type=str, 
        help="Path to the JSONL diagnostics file generated by the simulator."
    )
    return parser.parse_args()

def calculate_stats(episodes):
    if not episodes:
        return None
        
    total = len(episodes)
    success_count = sum(1 for ep in episodes if "arrive" in ep.get("termination", []))
    collision_count = sum(1 for ep in episodes if "collision" in ep.get("termination", []))
    timeout_count = sum(1 for ep in episodes if "time_out" in ep.get("termination", []))
    out_of_area_count = sum(1 for ep in episodes if "out_of_walkable_area" in ep.get("termination", []))
    
    # Custom deadlock check (either from extended json keys or custom rules)
    deadlock_count = sum(
        1 for ep in episodes 
        if ep.get("deadlock_detected", False) or "deadlock" in ep.get("termination", [])
    )
    
    # Average steps and return
    avg_steps = np.mean([ep.get("steps", 0) for ep in episodes])
    avg_return = np.mean([ep.get("episode_return", 0.0) for ep in episodes])
    avg_route_dist = np.mean([ep.get("route_distance_m", 0.0) for ep in episodes])
    
    # Optional advanced metrics (show only if present in JSONL)
    avg_lat_err = None
    min_obs_clr = None
    avg_driveway_fraction = None
    
    lat_errors = [ep["rewards"].get("avg_lateral_error_m") for ep in episodes if "avg_lateral_error_m" in ep.get("rewards", {})]
    if not lat_errors:
        # Check root level too
        lat_errors = [ep["avg_lateral_error_m"] for ep in episodes if "avg_lateral_error_m" in ep]
    if lat_errors:
        avg_lat_err = np.mean(lat_errors)
        
    obs_clearances = [ep.get("min_obstacle_clearance_m") for ep in episodes if "min_obstacle_clearance_m" in ep]
    if obs_clearances:
        min_obs_clr = np.min(obs_clearances)
        
    driveway_fractions = [ep.get("driveway_time_fraction") for ep in episodes if "driveway_time_fraction" in ep]
    if driveway_fractions:
        avg_driveway_fraction = np.mean(driveway_fractions)

    return {
        "total": total,
        "success_rate": success_count / total * 100,
        "collision_rate": collision_count / total * 100,
        "timeout_rate": timeout_count / total * 100,
        "out_of_area_rate": out_of_area_count / total * 100,
        "deadlock_rate": deadlock_count / total * 100,
        "avg_steps": avg_steps,
        "avg_return": avg_return,
        "avg_route_dist": avg_route_dist,
        "avg_lateral_error": avg_lat_err,
        "min_obs_clearance": min_obs_clr,
        "avg_driveway_fraction": avg_driveway_fraction,
    }

def print_stats_table(title, stats_dict):
    if not stats_dict:
        print(f"\n### {title}: No data available")
        return

    # Check if advanced metrics are present in any of the stats
    has_advanced = any(
        stats_dict[k]["avg_lateral_error"] is not None or 
        stats_dict[k]["min_obs_clearance"] is not None or
        stats_dict[k]["avg_driveway_fraction"] is not None
        for k in stats_dict
    )

    print(f"\n### {title}")
    
    headers = [
        "Group", "Total Ep", "Success %", "Collision %", "Timeout %", 
        "OutWalk %", "Deadlock %", "Avg Steps", "Avg Dist (m)"
    ]
    if has_advanced:
        headers.extend(["Avg LatErr (m)", "Min ObsClr (m)", "Driveway %"])
        
    header_row = " | ".join(headers)
    separator_row = " | ".join(["---"] * len(headers))
    print(f"| {header_row} |")
    print(f"| {separator_row} |")
    
    for group, stats in stats_dict.items():
        row = [
            f"**{group}**",
            f"{stats['total']}",
            f"{stats['success_rate']:.1f}%",
            f"{stats['collision_rate']:.1f}%",
            f"{stats['timeout_rate']:.1f}%",
            f"{stats['out_of_area_rate']:.1f}%",
            f"{stats['deadlock_rate']:.1f}%",
            f"{stats['avg_steps']:.1f}",
            f"{stats['avg_route_dist']:.2f}",
        ]
        if has_advanced:
            lat_err = f"{stats['avg_lateral_error']:.3f}" if stats['avg_lateral_error'] is not None else "-"
            obs_clr = f"{stats['min_obs_clearance']:.2f}" if stats['min_obs_clearance'] is not None else "-"
            drv_frac = f"{stats['avg_driveway_fraction'] * 100:.1f}%" if stats['avg_driveway_fraction'] is not None else "-"
            row.extend([lat_err, obs_clr, drv_frac])
            
        print(f"| {' | '.join(row)} |")

def main():
    args = parse_args()
    log_path = Path(args.log_file)
    
    if not log_path.exists():
        print(f"[ERROR] Log file does not exist: {log_path}", file=sys.stderr)
        sys.exit(1)
        
    episodes = []
    print(f"[*] Reading log file: {log_path}")
    
    with log_path.open("r", encoding="utf-8") as f:
        for idx, line in enumerate(f):
            # Parse only valid json lines
            line = line.strip()
            if not line:
                continue
                
            # If line is prefixed by "[S2E_AUTO_EPISODE] ", strip it
            if line.startswith("[S2E_AUTO_EPISODE] "):
                line = line[len("[S2E_AUTO_EPISODE] "):]
                
            try:
                data = json.loads(line)
                episodes.append(data)
            except json.JSONDecodeError:
                print(f"[WARNING] Skipping malformed JSON line at index {idx+1}")
                
    if not episodes:
        print("[ERROR] No valid episode data parsed from file.")
        sys.exit(1)
        
    print(f"[🟢 SUCCESS] Parsed {len(episodes)} episodes.")
    
    # 1. Overall stats
    overall = {"All Episodes": calculate_stats(episodes)}
    print_stats_table("Overall Performance Summary", overall)
    
    # 2. Stats grouped by curriculum/difficulty level
    level_groups = defaultdict(list)
    for ep in episodes:
        level_groups[f"Level {ep.get('curriculum_level', ep.get('difficulty', 0))}"].append(ep)
        
    level_stats = {}
    for lvl in sorted(level_groups.keys()):
        level_stats[lvl] = calculate_stats(level_groups[lvl])
    print_stats_table("Performance by Difficulty Level", level_stats)
    
    # 3. Stats grouped by obstacle scenario
    scenario_groups = defaultdict(list)
    for ep in episodes:
        scenario_groups[ep.get("scenario", "unknown")].append(ep)
        
    scenario_stats = {}
    for sc in sorted(scenario_groups.keys()):
        scenario_stats[sc] = calculate_stats(scenario_groups[sc])
    print_stats_table("Performance by Obstacle Scenario", scenario_stats)

if __name__ == "__main__":
    main()
